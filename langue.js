function changeLanguage(langue){
    var textes = textsInEnglish
    if (langue == "français"){
        textes = textesEnFrancais
    }
    Object.keys(textes).forEach(function(cle){
        var element = document.querySelector('#'+cle);
        if (element) {
          element.innerHTML = textes[cle];
        }
    })
};

document.querySelectorAll("input[name='langue']").forEach(function(input) {
  input.addEventListener('click', function(e) { changeLanguage(e.target.value); });
});
var langSaved = localStorage.getItem('langue');
if (langSaved) {
  var radio = document.querySelector("input[value='" + langSaved + "']");
  if (radio) radio.checked = true;
  changeLanguage(langSaved);
}

var menuToggle = document.getElementById('menu-toggle');
var navLinks = document.getElementById('nav-links');
if (menuToggle && navLinks) {
  menuToggle.addEventListener('click', function() {
    var ouvert = navLinks.classList.toggle('ouvert');
    menuToggle.setAttribute('aria-expanded', ouvert);
  });

  navLinks.querySelectorAll('a').forEach(function(lien) {
    lien.addEventListener('click', function() {
      navLinks.classList.remove('ouvert');
      menuToggle.setAttribute('aria-expanded', false);
    });
  });
}

